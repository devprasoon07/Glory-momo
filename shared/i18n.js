export function applyTranslations(lang = getCurrentLang()) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  // 1. Text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // 2. Weekday table rows in Opening Hours
  const daysMap = {
    '1': dict.day_monday || 'Monday',
    '2': dict.day_tuesday || 'Tuesday',
    '3': dict.day_wednesday || 'Wednesday',
    '4': dict.day_thursday || 'Thursday',
    '5': dict.day_friday || 'Friday',
    '6': dict.day_saturday || 'Saturday',
    '0': dict.day_sunday || 'Sunday',
  };
  document.querySelectorAll('[data-hours] tr[data-day]').forEach(tr => {
    const day = tr.dataset.day;
    const th = tr.querySelector('th');
    if (th && daysMap[day]) {
      th.textContent = daysMap[day];
    }
  });

  // 3. Payment method select dropdown options
  const paySelect = document.getElementById('cart-pay-select');
  if (paySelect) {
    const optUpi = paySelect.querySelector('option[value="upi"]');
    const optCod = paySelect.querySelector('option[value="cod"]');
    if (optUpi) optUpi.textContent = dict.opt_upi || optUpi.textContent;
    if (optCod) optCod.textContent = dict.opt_cod || optCod.textContent;
  }

  // 4. Update html lang attribute
  document.documentElement.lang = lang;
}
